<template>
    <!-- Chapter 05 · The Complete Closed-Loop Flywheel: Tree + Battery + Charger + Car with dual energy and buyback flow streams -->
    <section ref="sectionRef" data-chapter="05" class="relative bg-zinc-950 text-white" style="height: 520vh">
        <div class="sticky top-0 h-screen h-dvh w-full overflow-hidden">
            <div class="pointer-events-none absolute inset-0">
                <div :class="CONTAINER" class="relative h-full">
                    <div :class="VISUAL_AREA">
                        <Web3Ecosystem
                            :draw="s.draw"
                            :flow="s.flow"
                            :orbit="s.orbit"
                            :active="active"
                            tree-variant="v1"
                        />
                    </div>
                </div>
            </div>

            <InvestorChapterText
                index="05"
                label="05 · CLOSED-LOOP VALUE FLYWHEEL"
                :beats="beats"
                :state="[
                    { in: s.b0, out: s.b0out },
                    { in: s.b1, out: s.b1out },
                    { in: s.b2, out: 0 },
                ]"
                :mark="s.mark"
            />
        </div>
    </section>
</template>

<script setup lang="ts">
import gsap from 'gsap';
import { ScrollTrigger } from 'gsap/ScrollTrigger';
import { computed, onMounted, onUnmounted, reactive, ref } from 'vue';
import type { Beat } from '@/custom/investors/InvestorChapterText.vue';
import InvestorChapterText from '@/custom/investors/InvestorChapterText.vue';
import { CONTAINER, VISUAL_AREA } from '@/custom/investors/tokens';
import Web3Ecosystem from '@/custom/web3/Web3Ecosystem.vue';

gsap.registerPlugin(ScrollTrigger);

const beats = computed<Beat[]>(() => [
    {
        segments: [
            { text: 'Physical energy generation ', break: true },
            { text: 'powers continuous token scarcity.', tone: 'accent' },
        ],
        sub: 'Every kilowatt-hour generated by Treetino trees and utility batteries feeds commercial chargers, factories, and the grid. Every euro collected triggers programmatic market purchases of $TREE.',
        stats: [
            { value: '1 Billion', label: 'Fixed Hard Cap' },
            { value: 'Zero', label: 'Uncapped Inflation' },
            { value: 'Dual Flow', label: 'Energy & Cashflow' },
        ],
    },
    {
        segments: [
            { text: 'Dual-wire architecture: ', break: true },
            { text: 'kilowatt-hours on the ground, value on Solana.', tone: 'accent' },
        ],
        sub: 'Amber lines represent physical power flowing from tree to battery, charger and vehicle. Blue lines represent real monetary value flowing back into $TREE repurchases and irreversible burns.',
        stats: [
            { value: '<$0.001', label: 'Solana Tx Cost' },
            { value: '400 ms', label: 'Execution Speed' },
            { value: '100%', label: 'Public Auditability' },
        ],
    },
    {
        segments: [
            { text: 'Institutional alignment: ', break: true },
            { text: 'OpCo physical stability meets Web3 network scale.', tone: 'accent' },
        ],
        sub: 'Treetino OpCo carries audited manufacturing contracts, patents, and government grants. The $TREE protocol aggregates high-margin liquidity and rewards global decentralized network participants.',
        stats: [
            { value: '100%', label: 'Regulated Off-Grid OpCo' },
            { value: 'Non-Dilutive', label: 'Grant Backed' },
            { value: 'Compound', label: 'Self-Sustaining Loop' },
        ],
    },
]);

const sectionRef = ref<HTMLElement | null>(null);
const active = ref(false);

const s = reactive({
    mark: 0,
    draw: 0,
    flow: 0,
    orbit: 0,
    b0: 0,
    b0out: 0,
    b1: 0,
    b1out: 0,
    b2: 0,
});

let timeline: gsap.core.Timeline | null = null;
let visibility: ScrollTrigger | null = null;

onMounted(() => {
    visibility = ScrollTrigger.create({
        trigger: sectionRef.value,
        start: 'top bottom',
        end: 'bottom top',
        onToggle: (self) => (active.value = self.isActive),
    });

    timeline = gsap.timeline({
        defaults: { ease: 'none' },
        scrollTrigger: {
            trigger: sectionRef.value,
            start: 'top top',
            end: 'bottom bottom',
            scrub: 0.6,
            invalidateOnRefresh: true,
        },
    });

    timeline
        .to(s, { orbit: 1, duration: 10, ease: 'sine.inOut' }, 0)
        // beat 0 · draw complete 3D ecosystem: tree, battery container, EV charger, car
        .to(s, { mark: 1, duration: 0.4 }, 0)
        .to(s, { draw: 1, duration: 1.8 }, 0)
        .to(s, { b0: 1, duration: 1 }, 0.2)
        .to(s, { b0out: 1, duration: 0.4, ease: 'power1.in' }, 3.2)
        // beat 1 · flow streams ignite: amber energy on ground, blue buyback stream in air
        .to(s, { b1: 1, duration: 1 }, 3.6)
        .to(s, { flow: 1, duration: 2.0, ease: 'power1.out' }, 3.6)
        .to(s, { b1out: 1, duration: 0.4, ease: 'power1.in' }, 6.6)
        // beat 2 · institutional OpCo alignment
        .to(s, { b2: 1, duration: 1 }, 7.0)
        .to({}, { duration: 0.6 }, 9.4);

    requestAnimationFrame(() => ScrollTrigger.refresh());
});

onUnmounted(() => {
    visibility?.kill();
    timeline?.scrollTrigger?.kill();
    timeline?.kill();
});
</script>

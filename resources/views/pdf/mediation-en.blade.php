    <!-- Article II -->
    <h2 class="article-title">II. Subject of Agreement</h2>
    
    <p class="clause"><strong>2.1</strong> The Broker hereby undertakes to actively conduct brokerage and mediation activities on behalf of the Principal, aimed at enabling the Principal to conclude contracts of sale or supply contracts with third parties (hereinafter "<strong>Clients</strong>") for the supply of the Principal's products and solutions.</p>

    <p class="clause"><strong>2.2</strong> The subject of brokerage consists exclusively of the innovative products presented at www.treetino.com (and www.treetino.eu), specifically autonomous energy trees <strong>Treetino V1</strong>, <strong>Treetino V2</strong>, standalone vertical wind micro-turbines, and related technological accessories (hereinafter "<strong>Products</strong>").</p>

    <p class="clause"><strong>2.3</strong> The Broker is authorized to actively present and market the Products to prospective Clients. However, without prior express written power of attorney from the Principal, the Broker is not entitled to enter into contracts or accept financial or other performance on behalf of the Principal.</p>

    <!-- Article III -->
    <h2 class="article-title">III. Commission Terms and Payouts</h2>

    <p class="clause"><strong>3.1</strong> For procuring the opportunity to conclude a transaction with a Client, the Broker is entitled to a commission of <strong>3% of the net contract value excluding VAT</strong> for each successfully completed transaction, or a commission tier corresponding to the Broker's performance standing (Silver, Gold, Platinum). This entitlement also arises if the Broker establishes the verified lead and the final commercial negotiation is concluded by the Principal.</p>

    <p class="clause"><strong>3.2</strong> Entitlement to the commission arises exclusively upon full receipt and clearance of the Client's initial payment (deposit invoice or first contract milestone) into the Principal's bank account.</p>

    <p class="clause"><strong>3.3</strong> The commission is payable within 14 calendar days of receipt of payment from the Client, based on a compliant tax invoice duly issued by the Broker.</p>

    <!-- Article IV -->
    <h2 class="article-title">IV. Intellectual Property, Trade Secrets & NDA</h2>

    <p class="clause"><strong>4.1 Intellectual Property:</strong> The Broker acknowledges that the Products, software, and technologies are subject to patent, industrial design, utility model, and trademark protections owned by the Principal. The Broker is strictly prohibited from copying, reverse engineering, or assisting any third party in unauthorized utilization of the Principal's technology.</p>

    <p class="clause"><strong>4.2 Trade Secrets & Confidentiality:</strong> All technical, pricing, calculation models within the Treetino Pricing app, customer databases, and marketing strategies constitute proprietary trade secrets of the Principal.</p>

    <p class="clause"><strong>4.3 Confidentiality Obligation:</strong> The Broker undertakes to maintain strict confidentiality during the term of this Agreement and for a period of 5 (five) years following its termination; and indefinitely with respect to statutory trade secrets and proprietary technical know-how.</p>

    <!-- Article V -->
    <h2 class="article-title">V. Contractual Penalties and Damages</h2>

    <p class="clause"><strong>5.1</strong> In the event of any breach of the obligations specified in Article IV by the Broker, the Broker shall pay the Principal a contractual penalty of <strong>CZK 500,000 (five hundred thousand Czech Crowns)</strong> for each individual violation.</p>

    <p class="clause"><strong>5.2</strong> The right to claim full damages, loss of profits, and injunctive relief exceeding the contractual penalty remains completely unaffected and directly enforceable.</p>

    <!-- Article VI -->
    <h2 class="article-title">VI. Duration and Final Provisions</h2>

    <p class="clause"><strong>6.1</strong> This Agreement is concluded for an indefinite duration. Either Party may terminate this Agreement without giving cause by giving 1 month's written notice, commencing on the first day of the calendar month following delivery.</p>


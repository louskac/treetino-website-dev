interface I18nContextType {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextType>({
  locale: 'cs',
  setLocale: () => {},
  t: (key: string) => key,
});

export const I18nProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try {
      const saved = localStorage.getItem('treetino_locale') as Locale;
      if (saved === 'cs' || saved === 'en') return saved;
      const browserLang = navigator.language.slice(0, 2);
      return browserLang === 'cs' ? 'cs' : 'en';
    } catch {
      return 'cs';
    }
  });

  const setLocale = useCallback((newLocale: Locale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem('treetino_locale', newLocale);
      document.documentElement.lang = newLocale;
    } catch {
      // ignore
    }
  }, []);

  useEffect(() => {
    try {
      document.documentElement.lang = locale;
    } catch {
      // ignore
    }
  }, [locale]);

  const t = useCallback((key: string, params?: Record<string, string | number>): string => {
    const keys = key.split('.');
    let value: any = translations[locale];

    for (const k of keys) {
      if (value && typeof value === 'object' && k in value) {
        value = value[k];
      } else {
        // Fallback to other language or return key
        let fallbackVal: any = translations[locale === 'cs' ? 'en' : 'cs'];
        for (const fbK of keys) {
          if (fallbackVal && typeof fallbackVal === 'object' && fbK in fallbackVal) {
            fallbackVal = fallbackVal[fbK];
          } else {
            fallbackVal = undefined;
            break;
          }
        }
        value = fallbackVal !== undefined ? fallbackVal : key;
        break;
      }
    }

    if (typeof value !== 'string') {
      return key;
    }

    if (params) {
      return Object.entries(params).reduce((acc, [paramKey, paramVal]) => {
        return acc.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
      }, value);
    }

    return value;
  }, [locale]);

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
export default useI18n;
